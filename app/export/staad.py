"""Build STAAD.Pro .std text from StructuralModel."""

from __future__ import annotations

from pathlib import Path
import math
import textwrap
from dataclasses import replace
from typing import List, Union

from app.core.models import StructuralModel, SupportType
from app.database.materials import get_material
from app.database.sections import SectionDatabase

PathLike = Union[str, Path]


def extract_transverse_frame(model: StructuralModel, station: float) -> StructuralModel:
    """A true XY plane model, with the selected frame's own tributary loads."""
    nodes = {i: replace(n, z=0.0) for i, n in model.nodes.items() if abs(n.z-station) < 1e-6}
    members = {i: m for i, m in model.members.items() if m.start_node in nodes and m.end_node in nodes}
    out = StructuralModel(
        nodes=nodes, members=members,
        supports={i: s for i, s in model.supports.items() if i in nodes},
        load_cases=dict(model.load_cases), combinations=dict(model.combinations),
        member_loads=[l for l in model.member_loads if l.member_id in members],
        nodal_loads=[l for l in model.nodal_loads if l.node_id in nodes],
        metadata={**model.metadata, "staad_plane": True, "source_frame_z_m": station},
    )
    out.metadata.pop("export_frame_z", None)
    if any(abs(l.fz_kn_m) > 1e-12 for l in out.member_loads) or any(abs(l.fz_kn) > 1e-12 for l in out.nodal_loads):
        raise ValueError("A plane model cannot carry global Z loads. Select full SPACE export.")
    return out


def build_staad_std_text(
    model: StructuralModel,
    *,
    title: str = "PEB Designer export",
    section_db: SectionDatabase | None = None,
) -> str:
    """Return STAAD SPACE or transverse PLANE input as text."""
    if model.metadata.get("staad_native"):
        from app.export.staad_import import preserved_staad_text
        return preserved_staad_text(model)
    if model.metadata.get("export_frame_z") is not None:
        model = extract_transverse_frame(model, float(model.metadata["export_frame_z"]))
    if not model.nodes:
        raise ValueError("Cannot export an empty model.")
    for node in model.nodes.values():
        if not all(math.isfinite(v) for v in node.coords):
            raise ValueError(f"Non-finite coordinates at node {node.id}")
    for load in [*model.member_loads, *model.nodal_loads]:
        if load.load_case_id not in model.load_cases:
            raise ValueError(f"Unknown load case: {load.load_case_id}")
        target = getattr(load, "member_id", None)
        if target is not None and target not in model.members:
            raise ValueError(f"Unknown loaded member: {target}")
        target = getattr(load, "node_id", None)
        if target is not None and target not in model.nodes:
            raise ValueError(f"Unknown loaded node: {target}")
        if any(not math.isfinite(v) for v in vars(load).values() if isinstance(v, float)):
            raise ValueError("Non-finite load magnitude")

    meta = model.metadata
    analysis_mode = meta.get("staad_analysis", "linear")
    if analysis_mode not in ("linear", "pdelta"):
        raise ValueError("STAAD analysis must be linear or pdelta")
    iterations = meta.get("pdelta_iterations", 20)
    if type(iterations) is not int or not 1 <= iterations <= 100:
        raise ValueError("P-Delta iterations must be an integer from 1 to 100")
    lines: List[str] = [
        "STAAD PLANE" if meta.get("staad_plane") else "STAAD SPACE",
        f"* {title}",
        "* Generated by PEB Designer",
        "* Not validated for construction design.",
        "START JOB INFORMATION",
        "END JOB INFORMATION",
        "INPUT WIDTH 79",
        "UNIT METER KN",
    ]

    lines.append(f"* Target STAAD: {meta.get('staad_version', '')}")
    lines.append(f"* Design code: {meta.get('design_code', '')}")
    lines.append(f"* Load combination: {meta.get('load_combination_type', meta.get('design_code', ''))}")
    dl = meta.get("deflection_limits") or {}
    if dl:
        lines.append(
            "* Deflection limits: "
            f"rafter Span/{dl.get('rafter_total_load_L_over', '')} (DL+LL), "
            f"Span/{dl.get('rafter_live_load_L_over', '')} (LL); "
            f"sway H/{dl.get('column_wind_crane_H_over', '')} (W/Crane), "
            f"H/{dl.get('column_seismic_H_over', '')} (Seismic)"
        )
    lines.append(f"* Frame type: {meta.get('frame_type', '')}")
    if meta.get("staad_plane"):
        lines.append(f"* Transverse frame at building Z={meta['source_frame_z_m']:g} m; relocated to XY")

    lines.append(f"* Width: {meta.get('span_m', '')} m  Length: {meta.get('length_m', '')} m")
    lines.append(f"* Material default: {meta.get('default_material', '')}")
    lines.append(f"* Ext. col. base: {meta.get('ext_col_base', meta.get('support_type', ''))}")
    lines.append(
        f"* Purlin spacing: {meta.get('purlin_spacing_m', '')} m  "
        f"Girt spacing: {meta.get('girt_spacing_m', '')} m"
    )
    pc = meta.get("plate_catalog") or {}
    if pc:
        lines.append(
            "* Plate catalog (mm): "
            f"web depths={len(pc.get('web_depths_mm') or [])}, "
            f"tw={len(pc.get('web_thicknesses_mm') or [])}, "
            f"bf={len(pc.get('flange_widths_mm') or [])}, "
            f"tf={len(pc.get('flange_thicknesses_mm') or [])}"
        )
    le = meta.get("load_engine") or {}
    for note in le.get("assumptions", []):
        lines.append(f"* Load note: {note}")
    for note in meta.get("audit_warnings", []):
        lines.append(f"* REVIEW: {note}")
    for key, value in (meta.get("wind_seismic") or {}).items():
        lines.append(f"* Wind/seismic input metadata: {key} = {value}")

    lines.append("JOINT COORDINATES")
    for node in model.node_list():
        lines.append(f"{node.id} {node.x:.12g} {node.y:.12g} {node.z:.12g};")

    lines.append("MEMBER INCIDENCES")
    for member in model.member_list():
        lines.append(f"{member.id} {member.start_node} {member.end_node};")

    # Group members by section name for PROPERTY
    by_section = {}
    for m in model.member_list():
        if not m.section:
            continue
        by_section.setdefault(m.section, []).append(m.id)
    if by_section:
        lines.append("MEMBER PROPERTY INDIAN")
        for sec_name, ids in by_section.items():
            # STAAD Indian table names often match ISMB designations
            if sec_name.startswith("ISMB "):
                lines.append(f"{_id_ranges(ids)} TABLE ST {sec_name.replace(' ', '')}")
            else:
                section_db = section_db or SectionDatabase()
                sec = section_db.get(sec_name)
                # Prismatic welded I: the same depth at both ends. Dimensions in m.
                dims = [sec.depth_mm, sec.tw_mm, sec.depth_mm,
                        sec.width_mm, sec.tf_mm, sec.width_mm, sec.tf_mm]
                lines.append(f"* Section: {sec_name}")
                for mid in ids:
                    lines.append(f"{mid} TAPERED " + " ".join(f"{v / 1000:.8g}" for v in dims))

    materials = {}
    for member in model.member_list():
        if member.material:
            materials.setdefault(member.material, []).append(member.id)
    if materials:
        material_tags = {name: "STEEL" if len(materials) == 1 else f"STEEL_{name}" for name in materials}
        lines.append("DEFINE MATERIAL START")
        for name in materials:
            mat = get_material(name)
            lines.extend([f"* Steel grade {name}: fy={mat.fy_mpa:g} MPa, fu={mat.fu_mpa:g} MPa",
                          f"ISOTROPIC {material_tags[name]}", f"E {mat.e_mpa * 1000:.8g}",
                          "POISSON 0.3", f"DENSITY {mat.density_kg_m3 * 9.80665 / 1000:.8g}",
                          "ALPHA 1.2e-5", "DAMP 0.03", "TYPE STEEL",
                          f"STRENGTH FY {mat.fy_mpa*1000:g} FU {mat.fu_mpa*1000:g}"])
        lines.extend(["END DEFINE MATERIAL", "CONSTANTS"])
        if len(materials) == 1 and sum(len(ids) for ids in materials.values()) == len(model.members):
            lines.append("MATERIAL STEEL ALL")
        else:
            for name, ids in materials.items():
                lines.append(f"MATERIAL {material_tags[name]} MEMB {_id_ranges(ids)}")

    # Only secondary longitudinal members are treated as simple spans.
    # Portal rafters/columns and their moment-resisting joints stay continuous.
    if not meta.get("staad_plane") and meta.get("secondary_connection", "pinned") == "pinned":
        simple_spans = [m.id for m in model.member_list() if m.member_type in ("purlin", "girt")]
        if simple_spans:
            lines.extend(["MEMBER RELEASE",
                          f"{_id_ranges(simple_spans)} START MY MZ",
                          f"{_id_ranges(simple_spans)} END MY MZ"])

    # Supports from model
    pinned = [s.node_id for s in model.supports.values() if s.support_type == SupportType.PINNED]
    fixed = [s.node_id for s in model.supports.values() if s.support_type == SupportType.FIXED]
    if pinned or fixed:
        lines.append("SUPPORTS")
        for chunk in _chunks(pinned, 8):
            lines.append(f"{' '.join(str(i) for i in chunk)} PINNED")
        for chunk in _chunks(fixed, 8):
            lines.append(f"{' '.join(str(i) for i in chunk)} FIXED")

    # Load cases from model member loads
    case_ids = sorted({lc.id for lc in model.load_cases.values()})
    for case_id in case_ids:
        loads = [ml for ml in model.member_loads if ml.load_case_id == case_id]
        nodal = [nl for nl in model.nodal_loads if nl.load_case_id == case_id]
        lc = model.load_cases[case_id]
        load_type = {"seismic": "Seismic", "dead": "Dead", "live": "Live", "wind": "Wind"}.get(lc.load_type.lower(), "None")
        lines.append(f"LOAD {case_ids.index(case_id)+1} LOADTYPE {load_type.upper()} TITLE {lc.name}")
        if loads:
            lines.append("MEMBER LOAD")
        for ml in loads:
            if abs(ml.fy_kn_m) > 1e-12:
                lines.append(f"{ml.member_id} UNI GY {ml.fy_kn_m:.9g}")
            if abs(ml.fx_kn_m) > 1e-12:
                lines.append(f"{ml.member_id} UNI GX {ml.fx_kn_m:.9g}")
            if abs(ml.fz_kn_m) > 1e-12:
                lines.append(f"{ml.member_id} UNI GZ {ml.fz_kn_m:.9g}")
        if nodal:
            lines.append("JOINT LOAD")
            for nl in nodal:
                parts = [f"{axis} {value:.9g}" for axis, value in
                         (("FX", nl.fx_kn), ("FY", nl.fy_kn), ("FZ", nl.fz_kn)) if abs(value) > 1e-12]
                if parts:
                    lines.append(f"{nl.node_id} " + " ".join(parts))

    # Combinations
    combo_numbers = {}
    for i, combo in enumerate(model.combinations.values(), start=max(100, len(case_ids) + 1)):
        combo_numbers[combo.id] = i
        missing = set(combo.factors) - set(case_ids)
        if missing or not combo.factors:
            raise ValueError(f"Invalid combination {combo.id}: empty or undefined load cases {missing}")
        if analysis_mode == "pdelta":
            lines.extend([f"LOAD {i} LOADTYPE NONE TITLE {combo.name.replace(' ', '_')}", "REPEAT LOAD"])
        else:
            lines.append(f"LOAD COMB {i} {combo.name.replace(' ', '_')}")
        parts = []
        for case_id, factor in combo.factors.items():
            if not math.isfinite(factor):
                raise ValueError(f"Non-finite factor in combination {combo.id}")
            if case_id in case_ids:
                parts.append(f"{case_ids.index(case_id)+1} {factor:g}")
        if parts:
            lines.append(" ".join(parts))
        lines.append(f"* Source: {combo.source}")

    if model.load_cases and all(m.section and m.material for m in model.members.values()):
        analysis_command = (f"PDELTA {iterations} ANALYSIS SMALLDELTA PRINT STATICS CHECK"
                            if analysis_mode == "pdelta" else "PERFORM ANALYSIS PRINT STATICS CHECK")
        lines.extend([analysis_command, "PRINT SUPPORT REACTION",
                      "PRINT MEMBER FORCES"])
        strength = [combo_numbers[c.id] for c in model.combinations.values() if c.source != "Serviceability"]
        service = [combo_numbers[c.id] for c in model.combinations.values() if c.source == "Serviceability"]
        if strength or service:
            lines.append("DEFINE ENVELOPE")
            for ids, num, kind in ((strength, 1, "STRENGTH"), (service, 2, "SERVICEABILITY")):
                for chunk in _chunks(ids, 8):
                    lines.append(f"{_id_ranges(chunk)} ENVELOPE {num} TYPE {kind}")
            lines.append("END DEFINE ENVELOPE")
        if meta.get("export_design") and meta.get("design_code") == "IS800-2007-LSD" and strength:
            primary = [m for m in model.member_list() if m.member_type in ("column", "rafter")
                       and (m.section.startswith("ISMB ") or m.section.startswith("BU "))]
            if primary:
                lines.extend(["* Primary I members; full physical lengths, restraints require review",
                              "LOAD LIST ENVELOPE 1", "PARAMETER 1", "CODE IS800 LSD"])
                for m in primary:
                    mat = get_material(m.material)
                    length = meta.get("physical_member_lengths_m", {}).get(m.id, math.dist(model.nodes[m.start_node].coords, model.nodes[m.end_node].coords))
                    lines.extend([f"FYLD {mat.fy_mpa*1000:g} MEMB {m.id}",
                                  f"FU {mat.fu_mpa*1000:g} MEMB {m.id}",
                                  f"STP {2 if m.section.startswith('BU ') else 1} MEMB {m.id}",
                                  f"BEAM 1 MEMB {m.id}", f"TRACK 2 MEMB {m.id}",
                                  f"LX {length:.9g} MEMB {m.id}",
                                  f"LY {length:.9g} MEMB {m.id}", f"LZ {length:.9g} MEMB {m.id}"])
                for chunk in _chunks([m.id for m in primary], 8):
                    lines.append(f"CHECK CODE MEMB {_id_ranges(chunk)}")
            unchecked = sorted(set(model.members) - {m.id for m in primary})
            if unchecked:
                lines.append("* Members excluded from native design: " + _id_ranges(unchecked))
    lines.append("FINISH")
    formatted = []
    for line in lines:
        if line.startswith("*"):
            formatted.extend(textwrap.wrap(line, 78, subsequent_indent="* ") or ["*"])
        else:
            # STAAD continuation uses a trailing hyphen; keep complete tokens.
            while len(line) > 78:
                cut = line.rfind(" ", 0, 76)
                if cut <= 0:
                    raise ValueError("STAAD token exceeds input width")
                formatted.append(line[:cut] + " -")
                line = line[cut + 1:]
            formatted.append(line)
    return "\n".join(formatted) + "\n"


def _chunks(values: List[int], size: int) -> List[List[int]]:
    return [values[i : i + size] for i in range(0, len(values), size)]


def _id_ranges(ids: List[int]) -> str:
    ids = sorted(ids)
    if not ids:
        return ""
    parts = []
    start = prev = ids[0]
    for mid in ids[1:]:
        if mid == prev + 1:
            prev = mid
            continue
        parts.append(f"{start}" if start == prev else f"{start} TO {prev}")
        start = prev = mid
    parts.append(f"{start}" if start == prev else f"{start} TO {prev}")
    return " ".join(parts)


def export_staad_std(
    model: StructuralModel,
    path: PathLike,
    *,
    title: str = "PEB Designer export",
) -> Path:
    out = Path(path)
    out.write_text(build_staad_std_text(model, title=title), encoding="utf-8")
    return out


def staad_std_text(model: StructuralModel, title: str = "PEB Designer export") -> str:
    return build_staad_std_text(model, title=title)
